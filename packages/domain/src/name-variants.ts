/**
 * The short forms of the words of a name the table knows, lower case: the pet names of each word
 * that is a first name of `HYPOCORISTICS` (any word, so «Rossi Mario» and «Mario Rossi» alike),
 * never the name itself, never shorter than `MIN_SHORT_FORM`, never a word of
 * `SHORT_FORM_STOPLIST`.
 */
export function firstNameVariants(word: string): string[] {
  const name = word.normalize('NFC').toLowerCase()
  const out = new Set<string>()
  for (const pet of HYPOCORISTICS[name] ?? []) {
    if ([...pet].length >= MIN_SHORT_FORM && pet !== name && !SHORT_FORM_STOPLIST.has(pet)) {
      out.add(pet)
    }
  }
  return [...out]
}
